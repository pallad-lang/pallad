#[derive(Debug, Clone)]
pub enum Instr {
    LoadNone,
    LoadBool(bool),
    LoadInt(i64),
    LoadFloat(f64),
    LoadStr(String),
    LoadVar(String),
    StoreVar(String),
    Add,
    Sub,
    Mul,
    Div,
    IntDiv,
    Mod,
    And,
    Or,
    Neg,
    Not,
    CallBuiltin {
        name: String,
        argc: usize,
    },
    Pop,
}
